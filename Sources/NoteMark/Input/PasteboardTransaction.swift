import AppKit

/// Puts rich text on the general pasteboard for one native paste, then
/// restores the user's contents unless they copied something new meanwhile.
///
/// Saving the contents asks the copying app for every representation it
/// offers, including ones it would otherwise provide lazily. There is no API to
/// promise another app's data again, so representations the app cannot supply
/// at that moment, such as file promises, are not restored.
@MainActor struct PasteboardTransaction {
    /// nspasteboard.org markers asking clipboard managers not to record the
    /// temporary item.
    private static let markerTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType")
    ]

    private let saved: [[NSPasteboard.PasteboardType: Data]]
    private let changeCount: Int

    /// Replace the pasteboard with `rtf`. Returns nil, with the previous
    /// contents restored, when the pasteboard rejects it.
    static func begin(rtf: Data) -> PasteboardTransaction? {
        let item = NSPasteboardItem()
        guard item.setData(rtf, forType: .rtf) else { return nil }
        for type in markerTypes { item.setData(Data(), forType: type) }
        let pasteboard = NSPasteboard.general
        let saved = snapshot(of: pasteboard)
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            write(saved, to: pasteboard)
            return nil
        }
        return PasteboardTransaction(saved: saved, changeCount: pasteboard.changeCount)
    }

    /// Restore the saved contents if the pasteboard still holds our item.
    func restore() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount == changeCount else { return }
        Self.write(saved, to: pasteboard)
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var values: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { values[type] = data }
            }
            return values
        }
    }

    private static func write(_ items: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        let restored = items.map { values -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in values { item.setData(data, forType: type) }
            return item
        }
        pasteboard.clearContents()
        pasteboard.writeObjects(restored)
    }
}
